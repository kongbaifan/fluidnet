import {chromium,expect} from '@playwright/test';
import {testServer} from './browser-server.mjs';
import {FHD_CONTEXT,captureFhd} from './browser-viewport.mjs';
const server=await testServer(),browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({...FHD_CONTEXT}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const nav=route=>page.locator(`.rail-link[data-route="${route}"]`).click();
try{
  await page.goto(server.base+'/#modules');await expect(page.locator('[data-module-id="programmable_valve"]')).toBeVisible();
  await page.locator('[data-action="new-module"]').click();
  await page.locator('[name="name"]').fill('失败复现验收阀');await page.locator('[name="code"]').fill('REPLAY_ACCEPTANCE');
  await page.locator('#dialog-form button[type="submit"]').click();
  const good=await page.locator('#module-code').inputValue();
  const bad=good.replace(/(def evaluate\(self, ctx[^\n]*\n)/,'$1        raise ValueError("frozen replay marker")\n');
  expect(bad).not.toBe(good);await page.locator('#module-code').fill(bad);await page.locator('#module-code').blur();
  const failed=page.waitForResponse(r=>r.url().endsWith('/modules/versions')&&r.request().method()==='POST');
  await page.locator('[data-action="save-module-version"]').click();const response=await failed;expect(response.status()).toBe(422);
  const failure=(await response.json()).detail;expect(failure.replay).toBeTruthy();
  await expect(page.locator('[data-action="inspect-module-replay"]')).toBeVisible();
  // Fix the editor draft, then explicitly inspect the earlier frozen failure.
  await page.locator('#module-code').fill(good);await page.locator('#module-code').blur();
  await page.locator('[data-action="inspect-module-replay"]').click();
  await expect(page.locator('[data-module-replay]')).toBeVisible();
  await expect(page.locator('[data-replay-source]')).toContainText('frozen replay marker');
  const replayed=page.waitForResponse(r=>r.url().endsWith('/modules/replay')&&r.request().method()==='POST');
  await page.locator('[data-action="run-module-replay"]').click();const replay=await replayed;
  expect(replay.status(),await replay.text()).toBe(200);expect((await replay.json()).matched_failure).toBe(true);
  await expect(page.locator('[data-replay-result]')).toContainText('已复现同一');
  await expect(page.locator('[data-replay-error-line]')).toContainText('raise ValueError');
  await captureFhd(page,'artifacts/module-failure-replay.png');
  await page.locator('[data-action="close-module-replay"]').click();await nav('modules');
  await page.locator('[data-module-id="replay_acceptance"] [data-action="edit-module"]').click();
  await page.locator('[data-action="editor-tab"][data-value="code"]').first().click();
  await expect(page.locator('#module-code')).toHaveValue(good);
  // A module that passes its default release test but fails in a project at 40% opening.
  const conditional=good.replace(/(def evaluate\(self, ctx[^\n]*\n)/,'$1        if ctx.parameter("opening_ratio") < .5:\n            raise ValueError("project replay marker")\n');
  await page.locator('#module-code').fill(conditional);await page.locator('#module-code').blur();
  const published=page.waitForResponse(r=>r.url().endsWith('/modules/versions')&&r.request().method()==='POST');
  await page.locator('[data-action="save-module-version"]').click();const releaseResponse=await published;expect(releaseResponse.status()).toBe(201);const release=await releaseResponse.json();
  const opening=release.module.parameters.find(p=>p.id==='opening_ratio'),displayOpening=.4/(opening.unit?.display_scale||1)+(opening.unit?.display_offset||0);
  await expect(page.locator('[data-action="save-module-version"]')).toBeEnabled();await nav('modules');
  await page.locator('[data-module-id="replay_acceptance"] [data-action="module-example"]').click();
  await page.locator('[data-node="V1"]').dblclick();
  await page.locator('[data-float-id="V1"] input[type="number"][data-instance-param="opening_ratio"]').fill(String(displayOpening));
  await page.locator('[data-float-id="V1"] [data-action="apply-instance"]').click();
  await page.locator('#dialog-form button[type="submit"]').click();
  await page.locator('[data-float-id="V1"] [data-action="float-close"]').click();
  const queued=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/runs'&&r.request().method()==='POST');
  await page.locator('[data-action="run-project"][data-command="run"]').first().click();
  const runId=(await(await queued).json()).run_id;
  await expect.poll(async()=>(await(await page.request.get(server.base+'/api/v1/runs/'+runId)).json()).status).toBe('failed');
  await nav('runs');await page.locator('[data-action="refresh-archives"]').click();
  await page.locator(`[data-action="open-archive"][data-id="${runId}"]`).click();
  await page.locator(`[data-action="archive-module-replay"][data-id="${runId}"]`).click();
  await expect(page.locator('[data-replay-source]')).toContainText('project replay marker');
  const retry=page.waitForResponse(r=>r.url().endsWith('/modules/replay')&&r.request().method()==='POST');
  await page.locator('[data-action="run-module-replay"]').click();expect((await(await retry).json()).matched_failure).toBe(true);
  await expect(page.locator('[data-replay-result]')).toContainText('已复现同一');
  const unchanged=await(await page.request.get(server.base+'/api/v1/runs/'+runId)).json();
  expect(unchanged.status).toBe('failed');expect(unchanged.request.project.instances.find(n=>n.id==='V1').parameters.opening_ratio).toBe(.4);
  expect(errors).toEqual([]);console.log(JSON.stringify({frozenFailure:true,editorDraftPreserved:true,archivedFailure:true,errors}));
}finally{await browser.close();await server.close();}
