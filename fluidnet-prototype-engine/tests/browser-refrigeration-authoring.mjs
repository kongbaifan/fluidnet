import {chromium,expect} from '@playwright/test';
import {mkdirSync,writeFileSync} from 'node:fs';
import {testServer} from './browser-server.mjs';
import {FHD_CONTEXT,captureFhd} from './browser-viewport.mjs';

const server=await testServer(),browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({...FHD_CONTEXT}),errors=[],evidence={};
const output='artifacts/platform-extension/rf3';
mkdirSync(output,{recursive:true});
page.on('pageerror',error=>errors.push(error.message));
const submit=async()=>{await page.locator('#dialog-form button[type="submit"]').click();await expect(page.locator('#dialog-form')).toHaveCount(0);};
const edit=async()=>{
  await page.locator('.rail-link[data-route="modules"]').click();
  await page.locator('[data-module-id="author_cold_valve"] [data-action="edit-module"]').click();
  await page.locator('[data-action="editor-tab"][data-value="contract"]').first().click();
};
const suite=async()=>{
  const receipt=page.waitForResponse(r=>r.url().endsWith('/modules/test-suite')&&r.request().method()==='POST');
  await page.locator('[data-action="module-test-suite"]').click();
  const response=await receipt;expect(response.status()).toBe(200);
  const result=await response.json();await expect(page.locator('[data-action="module-test-suite"]')).toBeEnabled();return result;
};
try {
  await page.goto(server.base+'/#modules');
  await expect(page.locator('[data-module-id="isenthalpic_throttle"]')).toBeVisible();
  await page.locator('[data-action="new-module"]').click();
  await page.locator('[name="name"]').fill('作者制冷节流阀');
  await page.locator('[name="code"]').fill('AUTHOR_COLD_VALVE');
  await page.locator('[name="base"]').selectOption('template:refrigeration_throttle');
  await submit();
  await page.locator('[data-action="editor-tab"][data-value="contract"]').first().click();
  await page.locator('[data-action="validate-module-contract"]').click();
  await expect(page.locator('#module-output')).toContainText('Worker 入口与四阶段方法通过');
  await page.locator('[data-action="configure-module-tests"]').click();
  await expect(page.locator('#dialog-form')).toContainText('饱和液体');
  await expect(page.locator('[data-condition="temperature_k"]')).toHaveCount(0);
  await expect(page.locator('[data-suite-case="0"] [data-condition="inlet_pressure_pa"]')).toHaveValue('1350000');
  const forward=page.locator('[data-suite-case="0"]');
  await forward.locator('[data-suite-action="add-assertion"]').click();
  await forward.getByLabel('结果变量',{exact:true}).fill('D1.mass_flow_kg_s');
  await forward.getByLabel('预期值',{exact:true}).fill('0');
  const closed=page.locator('[data-suite-case="3"]');
  await closed.locator('[data-suite-action="add-assertion"]').click();
  await closed.getByLabel('结果变量',{exact:true}).fill('D1.mass_flow_kg_s');
  await closed.getByLabel('预期值',{exact:true}).fill('0');
  await submit();
  const failed=await suite();expect(failed.passed).toBe(false);
  expect(failed.cases[0].assertions[0].status).toBe('outside_tolerance');
  expect(failed.cases[3].passed).toBe(true);
  await expect(page.locator('#module-output')).toContainText('绝对误差');
  await page.locator('[data-action="configure-module-tests"]').click();
  await forward.getByLabel('结果变量',{exact:true}).fill('D1.in0.pressure_pa');
  await forward.getByLabel('预期值',{exact:true}).fill('1350000');
  await submit();
  const passed=await suite();expect(passed.passed,JSON.stringify(passed)).toBe(true);
  evidence.suite=passed.cases.map(c=>({id:c.id,passed:c.passed,input_hash:c.input_hash}));
  const publish=page.waitForResponse(r=>r.url().endsWith('/modules/versions')&&r.request().method()==='POST');
  await page.locator('[data-action="save-module-version"]').click();
  const release=await publish;expect(release.status(),await release.text()).toBe(201);
  evidence.release=await release.json();
  await expect(page.locator('[data-action="save-module-version"]')).toBeEnabled();
  await page.locator('.rail-link[data-route="modules"]').click();
  await page.locator('[data-module-id="author_cold_valve"] [data-action="test-module"]').click();
  await expect(page.getByLabel('测试入口压力',{exact:true})).toHaveValue('1350');
  await expect(page.getByLabel('测试入口温度',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('测试制冷剂',{exact:true})).toHaveValue('Ammonia');
  const bench=async()=>{
    const receipt=page.waitForResponse(r=>r.url().endsWith('/modules/test')&&r.request().method()==='POST');
    await page.locator('[data-action="run-bench"][data-command="run"]').click();
    const response=await receipt;expect(response.status(),await response.text()).toBe(200);
    const result=await response.json();await expect(page.locator('[data-action="run-bench"][data-command="run"]')).toBeEnabled();return result;
  };
  const linear=await bench();
  await page.locator('[data-bench-param="characteristic"]').fill('equal_percentage');
  await page.locator('[data-bench-param="characteristic"]').blur();
  const equal=await bench();
  expect(equal.frame.variables['D1.mass_flow_kg_s']).toBeLessThan(linear.frame.variables['D1.mass_flow_kg_s']);
  await expect(page.locator('[data-bench-q]')).not.toHaveText('—');
  await expect(page.locator('[data-bench-commits]')).toHaveText('1');
  await expect(page.locator('#bench-results')).toContainText('制冷流股');
  await captureFhd(page,output+'/bench.png');
  evidence.linear=linear.frame.variables['D1.mass_flow_kg_s'];evidence.equalPercentage=equal.frame.variables['D1.mass_flow_kg_s'];
  await page.locator('[data-action="save"]').first().click();
  await page.reload();await edit();
  await page.locator('[data-action="configure-module-tests"]').click();
  await expect(forward.getByLabel('预期值',{exact:true})).toHaveValue('1350000');
  await submit();
  await page.locator('[data-action="editor-tab"][data-value="code"]').first().click();
  const source=await page.locator('#module-code').inputValue();
  await page.locator('#module-code').fill(source.replace('point = ctx.refrigeration.throttle',"raise ValueError('author refrigeration error')\n        point = ctx.refrigeration.throttle"));
  await page.locator('[data-action="editor-tab"][data-value="contract"]').first().click();
  const rejected=page.waitForResponse(r=>r.url().endsWith('/modules/versions')&&r.request().method()==='POST');
  await page.locator('[data-action="save-module-version"]').click();
  expect((await rejected).status()).toBe(422);
  await page.locator('[data-action="module-error-line"]').first().click();
  const selection=await page.locator('#module-code').evaluate(e=>e.value.slice(e.selectionStart,e.selectionEnd));
  expect(selection).toContain('author refrigeration error');
  await page.locator('#module-code').fill(source);
  const versions=await(await page.request.get(server.base+'/api/v1/modules/author_cold_valve/versions')).json();
  expect(versions.versions).toHaveLength(1);
  expect(errors).toEqual([]);
  evidence.sourceLocation=true;evidence.errors=errors;
  writeFileSync(output+'/browser-validation.json',JSON.stringify(evidence,null,2));
  console.log(JSON.stringify({suite:evidence.suite,linear:evidence.linear,equalPercentage:evidence.equalPercentage,sourceLocation:true,errors}));
} catch(error) {
  await captureFhd(page,output+'/failure.png').catch(()=>{});
  console.error(JSON.stringify({errors,toast:await page.locator('#toast').textContent().catch(()=>null)}));throw error;
} finally {await browser.close();await server.close();}
