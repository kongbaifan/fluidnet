"""Structural interfaces; implementation and wire validation belong to the host."""
from __future__ import annotations

from collections.abc import Mapping, MutableMapping, Sequence
from typing import Literal, Protocol, TypeAlias

ScalarValue: TypeAlias = float | int | str | bool | None
JSONValue: TypeAlias = ScalarValue | list['JSONValue'] | dict[str, 'JSONValue']
DiagnosticSeverity: TypeAlias = Literal['info', 'warning', 'error']
RelationKind: TypeAlias = Literal['pipe', 'valve', 'pump', 'compressor', 'resistance']
CallbackPhase: TypeAlias = Literal['manual', 'initialize', 'evaluate', 'thermal', 'observe', 'jacobian', 'commit_step', 'finalize']
PortDataKind: TypeAlias = Literal['unavailable', 'trial', 'converged']
ChannelDataKind: TypeAlias = Literal['unavailable', 'hydraulic_trial', 'converged']
StateDataKind: TypeAlias = Literal['unavailable', 'initial', 'input_copy', 'candidate', 'module_committed']


class ExecutionInfo(Protocol):
    """Callback identity/data provenance; accepted_time_s is an owner watermark, not a state snapshot."""

    @property
    def phase(self) -> CallbackPhase: ...
    @property
    def time_s(self) -> float | None: ...
    @property
    def run_id(self) -> str | None: ...
    @property
    def instance_id(self) -> str | None: ...
    @property
    def request_id(self) -> str | None: ...
    @property
    def step_id(self) -> str | None: ...
    @property
    def iteration_id(self) -> int | None: ...
    @property
    def dt_s(self) -> float | None: ...
    @property
    def accepted_time_s(self) -> float | None: ...
    @property
    def port_data(self) -> PortDataKind: ...
    @property
    def channel_data(self) -> ChannelDataKind: ...
    @property
    def state_data(self) -> StateDataKind: ...


class PortState(Protocol):
    """Port quantities in SI; mass flow is positive into the device. Unknown = None."""

    @property
    def humidity_ratio_kg_kg(self) -> float | None: ...
    @property
    def relative_humidity(self) -> float | None: ...
    @property
    def enthalpy_j_kg_dry_air(self) -> float | None: ...
    @property
    def specific_heat_j_kg_dry_air_k(self) -> float | None: ...
    @property
    def dew_point_k(self) -> float | None: ...
    @property
    def wet_bulb_k(self) -> float | None: ...

    @property
    def pressure_pa(self) -> float | None: ...
    @property
    def temperature_k(self) -> float | None: ...
    @property
    def enthalpy_j_kg(self) -> float | None: ...
    @property
    def density_kg_m3(self) -> float | None: ...
    @property
    def viscosity_pa_s(self) -> float | None: ...
    @property
    def specific_heat_j_kg_k(self) -> float | None: ...
    @property
    def dry_air_mass_flow_kg_s(self) -> float | None: ...
    @property
    def mass_flow_kg_s(self) -> float | None: ...
    @property
    def quality(self) -> float | None: ...
    @property
    def composition(self) -> Mapping[str, float]: ...


class ChannelResult(Protocol):
    @property
    def heat_w(self) -> float: ...
    """Converged flow follows declared input -> output; pressure drop = p_in - p_out."""

    @property
    def dry_air_mass_flow_kg_s(self) -> float | None: ...
    @property
    def mass_flow_kg_s(self) -> float: ...
    @property
    def pressure_drop_pa(self) -> float: ...


class FluidState(Protocol):
    """Property-service result. Transport/caloric extras can be unavailable."""

    @property
    def humidity_ratio_kg_kg(self) -> float | None: ...
    @property
    def relative_humidity(self) -> float | None: ...
    @property
    def enthalpy_j_kg_dry_air(self) -> float | None: ...
    @property
    def specific_heat_j_kg_dry_air_k(self) -> float | None: ...
    @property
    def dew_point_k(self) -> float | None: ...
    @property
    def wet_bulb_k(self) -> float | None: ...

    @property
    def pressure_pa(self) -> float: ...
    @property
    def temperature_k(self) -> float: ...
    @property
    def enthalpy_j_kg(self) -> float: ...
    @property
    def density_kg_m3(self) -> float: ...
    @property
    def viscosity_pa_s(self) -> float | None: ...
    @property
    def specific_heat_j_kg_k(self) -> float | None: ...
    @property
    def thermal_conductivity_w_m_k(self) -> float | None: ...
    @property
    def entropy_j_kg_k(self) -> float | None: ...
    @property
    def internal_energy_j_kg(self) -> float | None: ...
    @property
    def cv_j_kg_k(self) -> float | None: ...
    @property
    def speed_of_sound_m_s(self) -> float | None: ...
    @property
    def phase(self) -> str: ...
    @property
    def quality(self) -> float | None: ...
    @property
    def composition(self) -> Mapping[str, float]: ...


class PropertyService(Protocol):
    """Lazy host service, selected per circuit; queries can raise ValueError."""

    def state_pt(self, pressure: float, temperature: float) -> FluidState: ...
    def state_ph(self, pressure: float, enthalpy: float) -> FluidState: ...
    def state_ps(self, pressure: float, entropy: float) -> FluidState: ...
    def state_pq(self, pressure: float, quality: float) -> FluidState: ...
    def state_tq(self, temperature: float, quality: float) -> FluidState: ...
    def state_du(self, density: float, internal_energy: float) -> FluidState: ...
    def saturation_t(self, pressure: float) -> float: ...
    def saturation_p(self, temperature: float) -> float: ...
    def limits(self) -> Mapping[str, float | None]: ...
    def humid_air(self, temperature: float, pressure: float, relative_humidity: float) -> Mapping[str, float]: ...


class NetworkRelation(Protocol):
    """Validated host relation; a channel's heat_w is heat added to its fluid (W)."""

    @property
    def relation_id(self) -> str: ...
    @property
    def kind(self) -> RelationKind: ...
    @property
    def channel(self) -> str: ...
    @property
    def parameters(self) -> Mapping[str, JSONValue]: ...


class NetworkBuilder(Protocol):
    """Host-provided relation collector. Call methods; do not instantiate this protocol."""

    @property
    def relations(self) -> Sequence[NetworkRelation]: ...

    def pipe(self, *, channel: str, length_m: float, diameter_m: float, roughness_m: float = 0.0,
             density_kg_m3: float | None = None, viscosity_pa_s: float | None = None,
             height_m: float = 0.0, heat_w: float = 0.0) -> None: ...

    def valve(self, *, channel: str, kv: float, opening: float, density_kg_m3: float | None = None,
              height_m: float = 0.0, heat_w: float = 0.0) -> None: ...

    def pump(self, *, channel: str, head_curve: list[list[float]], speed_ratio: float = 1.0,
             density_kg_m3: float | None = None, heat_w: float = 0.0) -> None: ...

    def compressor(self, *, channel: str, forced_mass_flow_kg_s: float) -> None: ...

    def resistance(self, *, channel: str, diameter_m: float, loss_coefficient: float,
                   density_kg_m3: float | None = None, heat_w: float = 0.0) -> None: ...


class Diagnostic(Protocol):
    @property
    def code(self) -> str: ...
    @property
    def message(self) -> str: ...
    @property
    def severity(self) -> DiagnosticSeverity: ...
    @property
    def instance_id(self) -> str | None: ...
    @property
    def field(self) -> str | None: ...


class EvaluateResult(Protocol):
    """Read-only result shape for host/test consumers; evaluate itself returns None."""

    @property
    def relations(self) -> Sequence[NetworkRelation]: ...
    @property
    def variables(self) -> Mapping[str, ScalarValue]: ...
    @property
    def diagnostics(self) -> Sequence[Diagnostic]: ...


class CommitResult(Protocol):
    """Host callback result, not a promise of whole-step atomic acceptance."""

    @property
    def state(self) -> Mapping[str, JSONValue]: ...
    @property
    def variables(self) -> Mapping[str, ScalarValue]: ...
    @property
    def diagnostics(self) -> Sequence[Diagnostic]: ...


class ModuleContext(Protocol):
    """Host-provided callback context. Only state is author-managed mutable data."""

    @property
    def time_s(self) -> float | None: ...
    @property
    def phase(self) -> CallbackPhase: ...
    @property
    def execution(self) -> ExecutionInfo: ...
    @property
    def parameters(self) -> Mapping[str, JSONValue]: ...
    @property
    def ports(self) -> Mapping[str, PortState]: ...
    @property
    def channels(self) -> Mapping[str, ChannelResult]: ...
    @property
    def state(self) -> MutableMapping[str, JSONValue]: ...
    @property
    def fluid(self) -> PropertyService: ...
    @property
    def net(self) -> NetworkBuilder: ...

    def parameter(self, name: str, default: JSONValue = None) -> JSONValue: ...
    def port(self, name: str) -> PortState: ...
    def channel(self, name: str) -> ChannelResult: ...
    def fluid_at(self, port_id: str) -> PropertyService: ...
    def var(self, name: str, value: ScalarValue) -> None: ...
    def diagnostic(self, code: str, message: str, severity: DiagnosticSeverity = 'warning') -> None: ...
    def log(self, message: str, level: DiagnosticSeverity = 'info') -> None: ...
    def heat(self, channel: str, heat_w: float) -> None: ...
    def derivative(self, channel: str, flow_slope_pa_per_kg_s: float,
                   port_pressure_derivatives: Mapping[str, float], smooth: bool = True) -> None: ...


class DeviceModule(Protocol):
    """Existing synchronous four-callback lifecycle, using the public context only."""

    def initialize(self, ctx: ModuleContext) -> None: ...
    def evaluate(self, ctx: ModuleContext) -> None: ...
    def commit_step(self, ctx: ModuleContext, dt_s: float) -> None: ...
    def finalize(self, ctx: ModuleContext) -> None: ...
