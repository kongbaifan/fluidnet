import { chromium, expect } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const output = resolve('.cache/studio-prototype-qa');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const checks = [], errors = [];
const page = await browser.newPage({ viewport: { width: 1366, height: 768 }, acceptDownloads: true });
page.on('pageerror', e => errors.push(e.message));
const nav = async route => { await page.evaluate(route => location.hash = route, route); await page.waitForTimeout(50); };
const click = (action, attrs = '') => page.locator(`[data-action="${action}"]${attrs}`).first().click();
const tab = value => click('editor-tab', `[data-value="${value}"]`);
const submit = () => page.locator('#dialog-form button[type="submit"]').click();
const exportState = async () => {
  await nav('settings'); await click('settings-tab', '[data-value="storage"]');
  const [download] = await Promise.all([page.waitForEvent('download'), click('export', '[data-format="prototype"]')]);
  return JSON.parse(await readFile(await download.path(), 'utf8'));
};
try {
  await page.goto(pathToFileURL(resolve('output/visualizations/fluidnet-studio-prototype.html')).href);
  await click('guided-demo');
  await expect(page.locator('.editor-tabs .active')).toContainText('通路设置');
  await click('check-channels');
  await expect(page.locator('#channel-feedback')).toContainText('通路检查通过');
  await tab('drawing');
  await click('add-port', '[data-domain="info"][data-direction="in"]');
  await page.locator('[data-port-field="name"]').fill('SIGNAL_IN');
  await page.locator('[data-port-field="name"]').press('Tab');
  await tab('attributes');
  await expect(page.locator('#variable-rows')).toContainText('SIGNAL_IN_VALUE');
  const notes = page.locator('[data-var-note]');
  await notes.first().fill('入口质量流量备注');
  await notes.first().press('Tab');
  await expect(page.locator('[data-var-display]').first()).toBeFocused();
  await tab('drawing');
  await page.locator('[data-draw-id][aria-label="端口 SIGNAL_IN"]').click();
  await click('delete-port');
  await expect(page.locator('[aria-label="端口 SIGNAL_IN"]')).toHaveCount(0);
  checks.push('Port creation, variable synchronization, protected definition editing and Tab focus');

  await tab('values');
  await page.locator('[data-filter="valueSearch"]').fill('OPENING');
  await click('bank-select', '[data-value="1"]');
  const bankOpening = page.locator('[data-value-id="param:opening"][data-bank="1"]');
  await bankOpening.fill('165');
  await click('apply-bank');
  await expect(page.locator('#toast')).toContainText('0 至 100');
  await expect(page.locator('[data-value-id="param:opening"][data-bank="-1"]')).toHaveValue('80.0000');
  await bankOpening.fill('65');
  await click('apply-bank'); await expect(page.locator('#dialog-form')).toContainText('65'); await submit();
  await expect(page.locator('[data-value-id="param:opening"][data-bank="-1"]')).toHaveValue('65.0000');
  await click('new-model');
  await page.getByRole('textbox', { name: '型号名称', exact: true }).fill('验收调节阀 · 65%');
  await submit();
  await expect(page.locator('.model-detail')).toContainText('验收调节阀');
  checks.push('Library value validation, atomic application and named model creation');

  await click('apply-model-to-instance'); await page.getByRole('combobox', { name: '目标设备' }).selectOption('V1'); await submit();
  const float = page.locator('[data-float-id="V1"]');
  await expect(float).toBeVisible();
  await expect(float).toContainText('当前 80 %');
  await expect(float.locator('[data-instance-param="opening"][type="number"]')).toHaveValue('65');
  await float.locator('[data-action="save"]').click();
  await expect(float).toContainText('草稿已保存');
  await expect(float.locator('[data-pending-for]')).toContainText('待应用');
  await float.locator('[data-action="apply-instance"]').click(); await submit();
  await expect(float).toContainText('当前 65 %');
  await expect(float.locator('[data-pending-for]')).toContainText('0 项待应用');
  const box = await float.boundingBox();
  if (box.y + box.height > 740) throw Error('Floating window exceeds the usable viewport');
  await float.locator('[data-action="float-close"]').click();
  await click('run-project', '[data-command="step"]');
  await expect(page.locator('#statusbar')).toContainText('已暂停');
  await expect(page.locator('#statusbar [data-live-time]')).toContainText('0.1');
  checks.push('Model to instance, saved draft versus applied value and first project step');

  await click('run-project', '[data-command="run"]');
  await nav('curves');
  await page.waitForTimeout(450);
  await expect(page.locator('.task-chip')).toContainText('1 个运行任务');
  await click('run-project', '[data-command="pause"]');
  const projectBefore = await page.locator('#statusbar [data-live-time]').textContent();
  await page.waitForTimeout(300);
  await expect(page.locator('#statusbar [data-live-time]')).toHaveText(projectBefore);
  await click('run-project', '[data-command="step"]');
  await expect(page.locator('#statusbar [data-live-time]')).not.toHaveText(projectBefore);
  await nav('workbench');
  await page.locator('[data-node="V1"]').dblclick();
  await expect(float).toBeVisible();
  await float.locator('[data-action="float-tab"][data-value="results"]').click();
  await float.locator('[data-action="device-curve"]').click();
  await expect(page.locator('#extra-charts')).toContainText('A 路调节阀');
  await expect(page.locator('#extra-charts path.chart-line')).toHaveCount(1);
  await page.screenshot({ path: resolve(output, 'curves-with-data.png') });
  await click('toggle-series', '[data-value="b"]');
  await expect(page.locator('#main-flow-chart path.chart-line')).toHaveCount(2);
  const hit = await page.locator('#main-flow-chart [data-chart-hit]').boundingBox();
  await page.mouse.move(hit.x + hit.width * .6, hit.y + hit.height * .5);
  await expect(page.locator('#main-flow-chart-readout')).toContainText('A 路流量');
  await nav('runs'); await click('record-project');
  await expect(page.locator('.run-details')).toContainText('"opening": 65');
  checks.push('Project tasks across pages, pause and step, variable-bound curves, cursor and parameter snapshots');

  await nav('controls');
  await page.locator('[data-control-name]').fill('验收控制程序');
  await page.locator('[data-control-setting="period"]').fill('200');
  await page.locator('[data-control-setting="period"]').press('Tab');
  await click('preview-control'); await expect(page.locator('#control-output')).toContainText('周期 200 ms');
  await click('choose-control-vars');
  await expect(page.locator('#dialog-form [name="output"] option[value="P1.OUT_TEMP"]')).toHaveCount(0);
  await submit();
  checks.push('Project control configuration, cycle preview and writable output targets');

  const state = await exportState();
  const device = state.projects.find(p => p.id === 'water-net').pages[0].nodes.find(n => n.id === 'V1');
  if (device.params.opening !== 65 || device.draft.opening !== 65) throw Error('Applied parameters were not retained');
  if (state.projects[0].controlConfig.period !== 200) throw Error('Control configuration did not persist');
  await click('save');
  await page.evaluate(()=>{const key='fluidnet-studio-prototype-20261009-v1',saved=JSON.parse(localStorage.getItem(key));saved.bench.run.status='running';localStorage.setItem(key,JSON.stringify(saved));});
  await page.reload();
  const restored = await exportState();
  if (restored.models.length !== state.models.length || restored.projects[0].controlConfig.name !== '验收控制程序') throw Error('Reload restoration failed');
  if (restored.bench.run.status !== 'paused' || restored.bench.run.time !== state.bench.run.time) throw Error('Retired bench continued running');
  await expect(page.locator('.task-chip')).toContainText('1 个运行任务');
  state.records.unshift({...structuredClone(state.records[0]),id:'LEGACY-TEST',name:'旧版单机测试记录',projectId:null,projectName:'调节阀 · 单机测试',moduleId:state.bench.moduleId,scope:'bench',mode:'单机测试',params:structuredClone(state.bench.params),boundary:structuredClone(state.bench.boundary)});
  await click('import');
  const invalid = { ...state, projects: [] };
  await page.locator('input[type="file"]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(invalid)) });
  await expect(page.locator('#import-preview')).toContainText('检查失败');
  await submit(); await expect(page.locator('#dialog-error')).toContainText('有效文件');
  await click('close-dialog');
  await click('import');
  await page.locator('input[type="file"]').setInputFiles({ name: 'roundtrip.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(state)) });
  await expect(page.locator('#import-preview')).toContainText('3 个项目'); await submit();
  await expect(page.locator('#dialog-form')).toHaveCount(0);
  await nav('runs');await click('select-record','[data-id="LEGACY-TEST"]');
  await expect(page.locator('.run-details')).toContainText('单机测试');
  await expect(page.locator('[data-route="bench"],[data-action="run-bench"],[data-action="bench-module"]')).toHaveCount(0);
  checks.push('Export, reload restore, retired bench stays inactive, legacy records remain readable without removed links, malformed import rejection and full JSON round-trip');

  await nav('workbench'); await page.locator('[data-node="V1"]').dblclick();
  await page.screenshot({ path: resolve(output, 'device-parameters.png') });
  const first = await float.boundingBox(), handle = await float.locator('.float-title').boundingBox();
  await page.mouse.move(handle.x + 20, handle.y + 6); await page.mouse.down(); await page.mouse.move(handle.x - 150, handle.y + 40, { steps: 6 }); await page.mouse.up();
  const moved = await float.boundingBox(); if (Math.abs(moved.x - first.x) < 50) throw Error('Window dragging failed');
  await float.locator('[data-action="float-min"]').click(); await expect(float.locator('.float-body')).toHaveCount(0);
  await float.locator('[data-action="float-min"]').click(); await expect(float.locator('.float-body')).toBeVisible();
  await page.locator('[data-node="P1"]').dblclick(); await expect(page.locator('.floater')).toHaveCount(2);
  await page.locator('[data-float-id="P1"] [data-action="float-close"]').click();
  await float.locator('[data-action="float-close"]').click();
  await page.locator('[data-node="V1"]').click(); await page.keyboard.press('Control+c'); await page.keyboard.press('Control+v');
  await expect(page.locator('#network [data-node]')).toHaveCount(10);
  await page.keyboard.press('Control+z'); await expect(page.locator('#network [data-node]')).toHaveCount(9);
  await page.keyboard.press('Control+y'); await expect(page.locator('#network [data-node]')).toHaveCount(10);
  checks.push('Window movement, minimize/restore, multiple windows and canvas copy/undo/redo');
  await click('theme'); await page.screenshot({ path: resolve(output, 'workbench-dark.png') });
  if (errors.length) throw Error(errors.join('\n'));
} catch (e) {
  await page.screenshot({ path: resolve(output, 'workflow-failure.png') });
  throw e;
} finally {
  await writeFile(resolve(output, 'workflow.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
  await browser.close();
}
